export function normalizeRedemptionCode(code: string) {
  const compact = code.toUpperCase().replace(/[^A-Z0-9]/g, '')

  if (compact.startsWith('VALKO') && compact.length === 13) {
    return `${compact.slice(0, 5)}-${compact.slice(5, 9)}-${compact.slice(9, 13)}`
  }

  return code.trim().toUpperCase().replace(/\s+/g, '-')
}

export async function hashRedemptionCode(code: string) {
  const normalizedCode = normalizeRedemptionCode(code)
  const bytes = new TextEncoder().encode(`${redemptionCodeSalt}:${normalizedCode}`)
  const digest = await window.crypto.subtle.digest('SHA-256', bytes)

  return Array.from(new Uint8Array(digest))
    .map((byte) => byte.toString(16).padStart(2, '0'))
    .join('')
}

export async function validateRedemptionCode(code: string) {
  if (!code.trim() || !window.crypto?.subtle) {
    return null
  }

  const normalizedCode = normalizeRedemptionCode(code)
  const codeHash = await hashRedemptionCode(normalizedCode)

  return redemptionCodeHashes.has(codeHash) ? { normalizedCode, codeHash } : null
}
